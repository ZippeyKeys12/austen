use std::error::Error;
use std::path::PathBuf;
use std::sync::Arc;

use austen_lib::gen_dsl::passes::DEFAULT_MAX_ARRAY_LENGTH;
use austen_lib::gen_dsl::{
    DEFAULT_HEAP_BASE, DEFAULT_HEAP_BYTES, Entropy, Env, Evaluator, Incoming, Region, TapeParser,
    TestCaseSize, TreeLinearizer, bind_size_args,
};
use austen_lib::spec::{SpecModule, transform};
use austen_lib::wire::AustenInput;
use austen_lib::{
    AnyEngine, AnyGenerator, AnyTreeEngine, EngineBuild, EngineRegistry, ProductionModules,
    TreeEngineFactory,
};
use austen_zero_biased_example::ZeroBiasedFactory;

// An embedding application owns its registry. This does not register an engine
// in an independently installed `austen` executable.
static ENGINES: &[AnyEngine] = &[AnyEngine::AustenDriven(AnyGenerator::Tree(
    AnyTreeEngine::new(&ZeroBiasedFactory),
))];
static REGISTRY: EngineRegistry = EngineRegistry::new(ENGINES);

fn main() -> Result<(), Box<dyn Error>> {
    let mut arguments = std::env::args_os().skip(1);
    let output = PathBuf::from(
        arguments
            .next()
            .ok_or("usage: austen-zero-biased-example OUTPUT_DIR")?,
    );
    if arguments.next().is_some() {
        return Err("usage: austen-zero-biased-example OUTPUT_DIR".into());
    }
    // A fresh directory prevents mixing generated bytes from different builds.
    std::fs::create_dir(&output)?;

    let spec = SpecModule::from_json(include_str!("../bias.json"))?;
    let factory = REGISTRY
        .resolve_tree("zero-biased")
        .ok_or("missing factory")?;
    let conversion = transform(&spec, factory.passes())?;
    let function = &conversion.functions[0];
    let wire = Arc::new(conversion.wire);
    let production = Arc::new(conversion.production);

    // This example has no pointer parameters, globals or memory writes. Its
    // numeric heap description is never dereferenced. A general campaign must
    // use the incoming map published by its actual harness instead.
    let heap = Region {
        base: DEFAULT_HEAP_BASE,
        size: DEFAULT_HEAP_BYTES,
    };
    let incoming = Incoming::from(heap);
    let mut producer = factory.open(EngineBuild {
        production_modules: ProductionModules::single(factory.passes(), Arc::clone(&production)),
        wire_module: Arc::clone(&wire),
        incoming: incoming.clone(),
        max_attempts: 64,
        max_array_length: DEFAULT_MAX_ARRAY_LENGTH,
        generator_timeout: None,
        entropy: Entropy::seeded(7),
        custom: None,
    })?;
    let size = TestCaseSize::new(25).ok_or("invalid size")?;
    let root = production
        .function_generator(&function.generator)?
        .root_call_with_size(size, heap);
    let wire_definition = wire.function_generator(&function.generator)?;
    let mut zeros = 0;

    for index in 0..16 {
        let evaluator = Evaluator::sampled(&wire, size, index, &function.post_defaults)?;
        let tree = producer.produce_with_evaluator(&root, &evaluator)?;
        let mut env = Env::new();
        bind_size_args(&mut env, wire_definition, size);
        let tape = TreeLinearizer::new(&wire, &incoming).linearize_with_evaluator(
            &wire_definition.body,
            env,
            &tree,
            &evaluator,
        )?;
        let mut env = Env::new();
        bind_size_args(&mut env, wire_definition, size);
        let parsed = TapeParser::new(&wire, &incoming).parse_with_defaults(
            &wire_definition.body,
            env,
            tape.as_bytes(),
            &function.post_defaults,
        )?;
        let args = parsed.args().ok_or("parser returned no C arguments")?;
        let [x] = args.as_slice() else {
            return Err("expected one scalar argument".into());
        };
        let input = AustenInput::from_parts(function.target_id, size, tape.into_bytes());
        std::fs::write(output.join(format!("{index:02}.input")), input.as_bytes())?;
        if *x == 0 {
            zeros += 1;
            std::fs::write(output.join("zero.input"), input.as_bytes())?;
        }
        println!("{index:02}.input: x = {x}");
    }
    if zeros == 0 {
        return Err("this sample did not draw zero".into());
    }
    println!(
        "Wrote 16 inputs ({zeros} zero arguments) to {}",
        output.display()
    );
    println!("Replay zero.input with the included bias.json and bias.c target.");
    Ok(())
}
